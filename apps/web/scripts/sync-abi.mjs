#!/usr/bin/env node
/**
 * Copies the ClaimVault ABI from the Foundry build into the frontend.
 *   pnpm --filter @alactic/web sync:abi            (default: ../../contracts/out/ClaimVault.sol/ClaimVault.json)
 *   pnpm --filter @alactic/web sync:abi path/to/ClaimVault.json
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] ?? resolve(here, "../../../contracts/out/ClaimVault.sol/ClaimVault.json"));
const out = resolve(here, "../lib/chain/abi/claimVault.ts");

let artifact;
try {
  artifact = JSON.parse(readFileSync(src, "utf8"));
} catch {
  console.error(`✗ Could not read ${src}. Run \`forge build\` in contracts/ first.`);
  process.exit(1);
}
const abi = artifact.abi ?? artifact;
writeFileSync(
  out,
  `/**\n * ClaimVault ABI — GENERATED by scripts/sync-abi.mjs from\n * ${src.replace(resolve(here, "../../.."), "<repo>")}\n * Do not edit by hand. Re-run \`pnpm --filter @alactic/web sync:abi\` after contract changes.\n */\nexport const claimVaultAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
const errors = abi.filter((x) => x.type === "error").map((x) => x.name);
console.log(`✓ Wrote ${abi.length} ABI entries to lib/chain/abi/claimVault.ts`);
console.log(`  Custom errors: ${errors.join(", ")}`);
console.log("  Check lib/chain/errors.ts has human copy for any new error names.");
